namespace Game.Core
{
    /// <summary>
    /// 편집 후 마차 연결을 어떤 기준으로 판정할지(설계 79번 §5.5). 전투로 마차가 파괴되면 대열이 끊어진 채 남을 수 있는데, 그 상태에서
    /// "모두 연결"만 허용하면 다시 잇는 중간 단계 편집(3덩어리 → 2덩어리)까지 전부 거부된다. 그래서 끊어진 대열을 다루는 정리 모드·마을
    /// 정비창은 "덩어리를 더 늘리지만 않으면 허용"을 쓴다. 편집 전이 이미 연결돼 있으면 두 기준의 결과는 같다.
    /// </summary>
    public enum ConnectivityRule
    {
        RequireConnected, // 최종 상태에서 모든 마차가 한 덩어리
        NoNewSplit,       // 최종 덩어리 수 ≤ 편집 전 덩어리 수
    }
}
